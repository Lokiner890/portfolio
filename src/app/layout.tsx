import '@/assets/styles/index.scss';

import type { Metadata } from 'next';
import { Red_Hat_Text } from 'next/font/google';

import { getAppUrl } from '@/lib/env';

const redHatText = Red_Hat_Text({
  subsets: ['latin'],
  display: 'swap',
  variable: '--font-red-hat-text',
});

// Defaults for every page, a page overrides fields with its own `metadata` export.
// Icons and the preview image come from the files in src/app: favicon.ico, opengraph-image.tsx.
// https://nextjs.org/docs/app/getting-started/metadata-and-og-images
export const metadata: Metadata = {
  // base for relative URLs in metadata (preview image, canonical links)
  metadataBase: new URL(getAppUrl()),
  // pages set their own `title`, shown as e.g. "LogIn | PROJECT_NAME"
  title: {
    default: 'PROJECT_NAME',
    template: '%s | PROJECT_NAME',
  },
  description: 'PROJECT_DESCRIPTION',
  openGraph: {
    type: 'website',
    siteName: 'PROJECT_NAME',
  },
  twitter: {
    card: 'summary_large_image',
  },
};

// LayoutProps: global type generated by `next typegen` from the routes in src/app
export default function RootLayout({ children }: LayoutProps<'/'>) {
  return (
    <html lang="en" className={redHatText.variable}>
      <body>{children}</body>
    </html>
  );
}
